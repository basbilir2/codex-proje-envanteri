import {build} from 'esbuild';
import {mkdir,copyFile,readFile,writeFile} from 'node:fs/promises';
await mkdir('dist',{recursive:true});
const worker=await build({entryPoints:['src/layout-worker.mjs'],bundle:true,format:'iife',minify:true,write:false});
await writeFile('src/layout-worker-code.mjs','// Generated by build.mjs\nexport default '+JSON.stringify(worker.outputFiles[0].text)+';\n');
await build({entryPoints:['src/studio.mjs'],outfile:'dist/dtf-studio.js',bundle:true,format:'esm',minify:true,external:['https://*']});
await copyFile('index.html','dist/index.html');
const code=await readFile('dist/dtf-studio.js','utf8');
const notices=await readFile('THIRD_PARTY_NOTICES.txt','utf8');
const html='<!doctype html><!--\n'+notices.replace(/--/g,'- -')+'\n--><html lang="tr"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>DTF Studio</title><style>html,body{margin:0;background:#f3f5f8}*{box-sizing:border-box}</style></head><body><dtf-studio></dtf-studio><script type="module">'+code.replace(/<\/script/gi,'<\\/script')+'</script></body></html>';
await writeFile('dist/DTF-Studio.html',html);
console.log('DTF Studio bundle ready.');
